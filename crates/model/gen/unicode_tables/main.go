// Command unicode_tables writes crates/model/src/unicode/tables.rs: the Unicode data that Go's regexp/syntax,
// strings, strconv and golang.org/x/text/unicode/norm use, taken from the Go toolchain itself so that the Rust
// port matches Go exactly (same Unicode version, same tables).
//
// Run from the repository root:
//
//	. tools/goenv.sh && (cd crates/model/gen/unicode_tables && GOFLAGS=-mod=mod GOPROXY=off go run .) > crates/model/src/unicode/tables.rs
package main

import (
	"fmt"
	"os"
	"bufio"
	"runtime"
	"sort"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

var w = bufio.NewWriter(os.Stdout)

func table(name string, t *unicode.RangeTable) {
	fmt.Fprintf(w, "&[")
	n := 0
	emit := func(lo, hi, stride uint32) {
		if n%6 == 0 {
			fmt.Fprintf(w, "\n    ")
		}
		fmt.Fprintf(w, "(0x%x, 0x%x, %d), ", lo, hi, stride)
		n++
	}
	for _, r := range t.R16 {
		emit(uint32(r.Lo), uint32(r.Hi), uint32(r.Stride))
	}
	for _, r := range t.R32 {
		emit(r.Lo, r.Hi, r.Stride)
	}
	fmt.Fprintf(w, "\n]")
}

func tables(kind string, m map[string]*unicode.RangeTable) {
	names := make([]string, 0, len(m))
	for k := range m {
		names = append(names, k)
	}
	sort.Strings(names)
	fmt.Fprintf(w, "pub(crate) static %s: &[(&str, &[(u32, u32, u32)])] = &[\n", kind)
	for _, n := range names {
		fmt.Fprintf(w, "(%q, ", n)
		table(n, m[n])
		fmt.Fprintf(w, "),\n")
	}
	fmt.Fprintf(w, "];\n\n")
}

func pairs(name string, f func(r rune) rune) {
	fmt.Fprintf(w, "pub(crate) static %s: &[(u32, u32)] = &[", name)
	n := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if t := f(r); t != r {
			if n%8 == 0 {
				fmt.Fprintf(w, "\n    ")
			}
			fmt.Fprintf(w, "(0x%x, 0x%x), ", r, t)
			n++
		}
	}
	fmt.Fprintf(w, "\n];\n\n")
}

func ranges(name string, f func(r rune) bool) {
	fmt.Fprintf(w, "pub(crate) static %s: &[(u32, u32)] = &[", name)
	n := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !f(r) {
			continue
		}
		lo := r
		for r+1 <= unicode.MaxRune && f(r+1) {
			r++
		}
		if n%8 == 0 {
			fmt.Fprintf(w, "\n    ")
		}
		fmt.Fprintf(w, "(0x%x, 0x%x), ", lo, r)
		n++
	}
	fmt.Fprintf(w, "\n];\n\n")
}

func main() {
	defer w.Flush()
	fmt.Fprintf(w, "// Code generated by crates/model/gen/unicode_tables from %s (unicode %s) and\n", runtime.Version(), unicode.Version)
	fmt.Fprintf(w, "// golang.org/x/text/unicode/norm (unicode %s). DO NOT EDIT.\n\n", norm.Version)
	fmt.Fprintf(w, "pub const UNICODE_VERSION: &str = %q;\n\n", unicode.Version)
	tables("CATEGORIES", unicode.Categories)
	tables("SCRIPTS", unicode.Scripts)
	tables("FOLD_CATEGORY", unicode.FoldCategory)
	tables("FOLD_SCRIPT", unicode.FoldScript)
	pairs("SIMPLE_FOLD", unicode.SimpleFold)
	pairs("TO_LOWER", unicode.ToLower)
	pairs("TO_UPPER", unicode.ToUpper)
	ranges("PRINT", unicode.IsPrint)

	// NFKD: full decomposition of each rune that changes (Hangul syllables are done algorithmically),
	// and the canonical combining class of each non-starter.
	fmt.Fprintf(w, "pub(crate) static NFKD: &[(u32, &[u32])] = &[\n")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xAC00 && r <= 0xD7A3 || r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		s := string(r)
		d := norm.NFKD.String(s)
		if d == s {
			continue
		}
		fmt.Fprintf(w, "    (0x%x, &[", r)
		for _, c := range d {
			fmt.Fprintf(w, "0x%x, ", c)
		}
		fmt.Fprintf(w, "]),\n")
	}
	fmt.Fprintf(w, "];\n\n")
	fmt.Fprintf(w, "pub(crate) static CCC: &[(u32, u32, u8)] = &[")
	n := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		c := norm.NFKD.PropertiesString(string(r)).CCC()
		if c == 0 {
			continue
		}
		lo := r
		for r+1 <= unicode.MaxRune && norm.NFKD.PropertiesString(string(r+1)).CCC() == c {
			r++
		}
		if n%6 == 0 {
			fmt.Fprintf(w, "\n    ")
		}
		fmt.Fprintf(w, "(0x%x, 0x%x, %d), ", lo, r, c)
		n++
	}
	fmt.Fprintf(w, "\n];\n")
}
