/// Go `alertMetricName`: the metric name for synthetic alert time series.
pub const ALERT_METRIC_NAME: &str = "ALERTS";
/// Go `alertForStateMetricName`: the metric name for the 'for' state of alerts.
pub const ALERT_FOR_STATE_METRIC_NAME: &str = "ALERTS_FOR_STATE";
/// Go `alertStateLabel`.
pub const ALERT_STATE_LABEL: &str = "alertstate";

static DUPLICATE_ALERT_LABEL_SET: Sentinel =
    Sentinel::new("vector contains metrics with the same labelset after applying alert labels");
/// Go `ErrDuplicateAlertLabelSet`.
pub const ERR_DUPLICATE_ALERT_LABEL_SET: Error = Error::Sentinel(&DUPLICATE_ALERT_LABEL_SET);

/// Go `resolvedRetention`: how long a resolved alert is kept (and re-sent).
pub const RESOLVED_RETENTION: Duration = Duration::from_secs(15 * 60);

/// Go `AlertState`.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug, Default, Hash)]
pub enum AlertState {
    /// Not yet evaluated.
    #[default]
    Unknown = 0,
    /// Neither firing nor pending.
    Inactive = 1,
    /// Active for less than the hold duration.
    Pending = 2,
    /// Active for at least the hold duration.
    Firing = 3,
}

impl AlertState {
    pub fn as_str(self) -> &'static str {
        match self {
            AlertState::Unknown => "unknown",
            AlertState::Inactive => "inactive",
            AlertState::Pending => "pending",
            AlertState::Firing => "firing",
        }
    }
}

impl std::fmt::Display for AlertState {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Go `Alert`: one instance of an alerting rule.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Alert {
    pub state: AlertState,
    pub labels: Labels,
    pub annotations: Labels,
    /// The value at the last evaluation of the alerting expression.
    pub value: f64,
    pub active_at: Time,
    pub fired_at: Time,
    pub resolved_at: Time,
    pub last_sent_at: Time,
    pub valid_until: Time,
    pub keep_firing_since: Time,
}

impl Alert {
    /// Go `needsSending`.
    pub fn needs_sending(&self, ts: Time, resend_delay: Duration) -> bool {
        if self.state == AlertState::Pending {
            return false;
        }
        // If an alert has been resolved since the last send, resend it.
        if self.resolved_at.after(self.last_sent_at) {
            return true;
        }
        self.last_sent_at.add(resend_delay).before(ts)
    }
}

/// Go `NotifyFunc`: sends notifications about alerts generated by the expression.
pub type NotifyFunc = std::sync::Arc<dyn Fn(&Context, &str, Vec<Alert>) + Send + Sync>;

/// Go `AlertingRule`: generates alerts from its vector expression.
pub struct AlertingRule {
    name: String,
    vector: Option<Expr>,
    hold_duration: Duration,
    keep_firing_for: Duration,
    labels: Labels,
    annotations: Labels,
    external_labels: HashMap<String, String>,
    external_url: String,
    restored: AtomicBool,
    state: RuleState,
    /// The active alerts (pending or firing, and resolved ones within the retention), keyed by label hash.
    active: Mutex<HashMap<u64, Alert>>,
    logger: Logger,
}

impl AlertingRule {
    /// Go `NewAlertingRule`.
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        name: &str,
        vec: impl Into<Option<Expr>>,
        hold: Duration,
        keep_firing_for: Duration,
        labels: Labels,
        annotations: Labels,
        external_labels: Labels,
        external_url: &str,
        restored: bool,
        logger: Logger,
    ) -> AlertingRule {
        AlertingRule {
            name: name.to_string(),
            vector: vec.into(),
            hold_duration: hold,
            keep_firing_for,
            labels,
            annotations,
            external_labels: external_labels.map(),
            external_url: external_url.to_string(),
            restored: AtomicBool::new(restored),
            state: RuleState::default(),
            active: Mutex::new(HashMap::new()),
            logger,
        }
    }

    /// Sets the hold duration (Go tests set `r.holdDuration`).
    pub fn set_hold_duration(&mut self, d: Duration) {
        self.hold_duration = d;
    }
    /// Sets the expression (Go tests set `r.vector`).
    pub fn set_vector(&mut self, e: Option<Expr>) {
        self.vector = e;
    }

    /// Go `HoldDuration`.
    pub fn hold_duration(&self) -> Duration {
        self.hold_duration
    }
    /// Go `KeepFiringFor`.
    pub fn keep_firing_for(&self) -> Duration {
        self.keep_firing_for
    }
    /// Go `Annotations`.
    pub fn annotations(&self) -> &Labels {
        &self.annotations
    }
    /// Go `SetRestored`.
    pub fn set_restored(&self, restored: bool) {
        self.restored.store(restored, Ordering::SeqCst);
    }
    /// Go `Restored`.
    pub fn restored(&self) -> bool {
        self.restored.load(Ordering::SeqCst)
    }

    /// Go `sample`: the ALERTS sample of an alert.
    pub fn sample(&self, alert: &Alert, ts: Time) -> Sample {
        let mut lb = Builder::new(self.labels.clone());
        alert.labels.range(|n, v| {
            lb.set(n, v);
        });
        lb.set(labels::METRIC_NAME, ALERT_METRIC_NAME);
        lb.set(labels::ALERT_NAME, &self.name);
        lb.set(ALERT_STATE_LABEL, alert.state.as_str());
        Sample { metric: lb.labels(), t: ts.millis(), f: 1.0, h: None, drop_name: false }
    }

    /// Go `forStateSample`: the ALERTS_FOR_STATE sample with the rule labels (and the alert's if given).
    pub fn for_state_sample(&self, alert: Option<&Alert>, ts: Time, v: f64) -> Sample {
        let mut lb = Builder::new(self.labels.clone());
        if let Some(a) = alert {
            a.labels.range(|n, v| {
                lb.set(n, v);
            });
        }
        lb.set(labels::METRIC_NAME, ALERT_FOR_STATE_METRIC_NAME);
        lb.set(labels::ALERT_NAME, &self.name);
        Sample { metric: lb.labels(), t: ts.millis(), f: v, h: None, drop_name: false }
    }

    /// Go `QueryForStateSeries`: the ALERTS_FOR_STATE series of the rule.
    pub fn query_for_state_series(&self, ctx: &Context, q: &dyn Querier) -> Result<BoxSeriesSet, Error> {
        let smpl = self.for_state_sample(None, Time::now(), 0.0);
        let mut matchers = Vec::new();
        smpl.metric.range(|n, v| {
            // Skip labels with template syntax: their values are expanded per alert instance and would not
            // match the stored series.
            if v.contains("{{") {
                return;
            }
            matchers.push(Matcher::new(MatchType::Equal, n, v).expect("equal matcher"));
        });
        let sset = q.select(ctx, false, None, &matchers);
        match sset.err() {
            Some(e) => Err(e),
            None => Ok(sset),
        }
    }

    /// Go `State`: the maximum state of the alert instances. Unknown before the first evaluation.
    pub fn state(&self) -> AlertState {
        let active = self.active.lock().unwrap();
        if self.state.evaluation_timestamp().is_zero() {
            return AlertState::Unknown;
        }
        let mut max = AlertState::Inactive;
        for a in active.values() {
            if a.state > max {
                max = a.state;
            }
        }
        max
    }

    /// Go `ActiveAlerts`: copies of the alerts that are not resolved.
    pub fn active_alerts(&self) -> Vec<Alert> {
        self.current_alerts().into_iter().filter(|a| a.resolved_at.is_zero()).collect()
    }

    /// Go `currentAlerts`: copies of all alert instances, including resolved ones.
    pub fn current_alerts(&self) -> Vec<Alert> {
        self.active.lock().unwrap().values().cloned().collect()
    }

    /// Go `ForEachActiveAlert`: runs `f` on each alert (not a copy).
    pub fn for_each_active_alert(&self, mut f: impl FnMut(&mut Alert)) {
        let mut active = self.active.lock().unwrap();
        for a in active.values_mut() {
            f(a);
        }
    }

    /// Go `ActiveAlertsCount`.
    pub fn active_alerts_count(&self) -> usize {
        self.active.lock().unwrap().len()
    }

    /// The map of active alerts (Go `r.active`, used by the manager to copy state and by tests).
    pub fn active_map(&self) -> std::sync::MutexGuard<'_, HashMap<u64, Alert>> {
        self.active.lock().unwrap()
    }

    /// Go `sendAlerts`.
    pub fn send_alerts(&self, ctx: &Context, ts: Time, resend_delay: Duration, interval: Duration, notify: &NotifyFunc) {
        let mut alerts = Vec::new();
        self.for_each_active_alert(|alert| {
            if alert.needs_sending(ts, resend_delay) {
                alert.last_sent_at = ts;
                // Allow for two Eval or Alertmanager send failures.
                let delta = interval.max(resend_delay);
                alert.valid_until = ts.add(delta * 4);
                alerts.push(alert.clone());
            }
        });
        notify(ctx, &self.expr_string(), alerts);
    }

    fn expand(&self, ctx: &Context, text: &str, smpl: &Sample, l: &HashMap<String, String>, ts: Time, query: &QueryFunc, external_url: Option<&str>) -> String {
        let defs = "{{$labels := .Labels}}{{$externalLabels := .ExternalLabels}}{{$externalURL := .ExternalURL}}{{$value := .Value}}";
        let full = format!("{defs}{text}");
        let name = format!("__alert_{}", self.name);
        match crate::tmpl::expand_alert(ctx, &full, &name, l, &self.external_labels, &self.external_url, smpl, ts, query, external_url) {
            Ok(s) => s,
            Err((e, data)) => {
                self.logger.warn("Expanding alert template failed", &[("err", &e), ("data", &data)]);
                format!("<error expanding template: {e}>")
            }
        }
    }
}

impl AlertingRule {
    /// The expression as text (Go `vector.String()`).
    pub fn expr_string(&self) -> String {
        self.vector.as_ref().map(|e| e.to_string()).unwrap_or_default()
    }
}

impl Rule for AlertingRule {
    fn name(&self) -> &str {
        &self.name
    }
    fn labels(&self) -> &Labels {
        &self.labels
    }

    /// Go `Eval`: evaluates the expression, creates pending alerts and fires or removes earlier ones.
    fn eval(&self, ctx: &Context, query_offset: Duration, ts: Time, query: &QueryFunc, external_url: Option<&str>, limit: i64) -> Result<Vector, Error> {
        let ctx = new_origin_context(ctx, new_rule_detail(self));
        let res = query(&ctx, &self.expr_string(), ts.sub_dur(query_offset))?;

        // Create pending alerts for any new vector elements in the alert expression or update the expression
        // value for existing elements.
        let mut result_fps = std::collections::HashSet::new();
        let mut lb = Builder::new(labels::empty_labels());
        let mut sb = ScratchBuilder::new(0);
        let mut vec = Vector::new();
        let mut alerts: Vec<(u64, Alert)> = Vec::with_capacity(res.len());
        for smpl in &res {
            // Provide the alert information to the template.
            let l = smpl.metric.map();

            lb.reset(smpl.metric.clone());
            lb.del(labels::METRIC_NAME);
            self.labels.range(|n, v| {
                let e = self.expand(&ctx, v, smpl, &l, ts, query, external_url);
                lb.set(n, &e);
            });
            lb.set(labels::ALERT_NAME, &self.name);

            sb.reset();
            self.annotations.range(|n, v| {
                let e = self.expand(&ctx, v, smpl, &l, ts, query, external_url);
                sb.add(n, &e);
            });
            let annotations = sb.labels();

            let lbs = lb.labels();
            let h = lbs.hash();
            result_fps.insert(h);

            if alerts.iter().any(|(k, _)| *k == h) {
                return Err(ERR_DUPLICATE_ALERT_LABEL_SET);
            }
            alerts.push((h, Alert { labels: lbs, annotations, active_at: ts, state: AlertState::Pending, value: smpl.f, ..Default::default() }));
        }

        let mut active = self.active.lock().unwrap();
        for (h, a) in alerts {
            // Update the last value and annotations of existing alerts, create new entries otherwise.
            if let Some(alert) = active.get_mut(&h)
                && alert.state != AlertState::Inactive
            {
                alert.value = a.value;
                alert.annotations = a.annotations;
                continue;
            }
            active.insert(h, a);
        }

        let mut num_active_pending = 0i64;
        let hold = dur_nanos(self.hold_duration);
        let keep_for = dur_nanos(self.keep_firing_for);
        let restored = self.restored.load(Ordering::SeqCst);
        let mut delete = Vec::new();
        // Check if any pending alerts should be removed or fire now. Write out alert time series.
        for (fp, a) in active.iter_mut() {
            if !result_fps.contains(fp) {
                // The alert is no longer firing. Use keep_firing_for to determine if it should keep firing.
                let mut keep_firing = false;
                if a.state == AlertState::Firing && keep_for > 0 {
                    if a.keep_firing_since.is_zero() {
                        a.keep_firing_since = ts;
                    }
                    if ts.sub(a.keep_firing_since) < keep_for {
                        keep_firing = true;
                    }
                }
                // Resolved alerts are kept for the retention period, so that resolved notifications are not
                // lost.
                if a.state == AlertState::Pending || (!a.resolved_at.is_zero() && ts.sub(a.resolved_at) > dur_nanos(RESOLVED_RETENTION)) {
                    delete.push(*fp);
                }
                if a.state != AlertState::Inactive && !keep_firing {
                    a.state = AlertState::Inactive;
                    a.resolved_at = ts;
                }
                if !keep_firing {
                    continue;
                }
            } else {
                // The alert is firing, reset keep_firing_since.
                a.keep_firing_since = Time::ZERO;
            }
            num_active_pending += 1;

            if a.state == AlertState::Pending && ts.sub(a.active_at) >= hold {
                a.state = AlertState::Firing;
                a.fired_at = ts;
            }

            // If the alert is firing and the active time is less than the new hold duration, set it to pending.
            if a.state == AlertState::Firing && ts.sub(a.active_at) < hold {
                a.state = AlertState::Pending;
                a.fired_at = Time::ZERO;
                a.last_sent_at = Time::ZERO;
                a.keep_firing_since = Time::ZERO;
            }

            if restored {
                vec.push(self.sample(a, ts.sub_dur(query_offset)));
                vec.push(self.for_state_sample(Some(a), ts.sub_dur(query_offset), a.active_at.unix_secs() as f64));
            }
        }
        // Go deletes from the map while ranging over it; an entry deleted there is still processed in the same
        // iteration, as here.
        for fp in delete {
            active.remove(&fp);
        }

        if limit > 0 && num_active_pending > limit {
            active.clear();
            return Err(Error::msg(format!("exceeded limit of {limit} with {num_active_pending} alerts")));
        }
        Ok(vec)
    }

    fn string(&self) -> String {
        rulefmt::Rule {
            alert: self.name.clone(),
            expr: self.expr_string(),
            r#for: yaml::Duration(dur_nanos(self.hold_duration)),
            keep_firing_for: yaml::Duration(dur_nanos(self.keep_firing_for)),
            labels: self.labels.map().into_iter().collect(),
            annotations: self.annotations.map().into_iter().collect(),
            ..Default::default()
        }
        .to_yaml()
    }
    fn query(&self) -> Option<&Expr> {
        self.vector.as_ref()
    }
    fn set_last_error(&self, err: Option<Error>) {
        self.state.set_last_error(err)
    }
    fn last_error(&self) -> Option<Error> {
        self.state.last_error()
    }
    fn set_health(&self, h: RuleHealth) {
        self.state.set_health(h)
    }
    fn health(&self) -> RuleHealth {
        self.state.health()
    }
    fn set_evaluation_duration(&self, d: Duration) {
        self.state.set_evaluation_duration(d)
    }
    fn get_evaluation_duration(&self) -> Duration {
        self.state.evaluation_duration()
    }
    fn set_evaluation_timestamp(&self, t: Time) {
        self.state.set_evaluation_timestamp(t)
    }
    fn get_evaluation_timestamp(&self) -> Time {
        self.state.evaluation_timestamp()
    }
    fn set_dependent_rules(&self, rules: &[RuleRef]) {
        self.state.set_dependents(rules)
    }
    fn no_dependent_rules(&self) -> bool {
        self.state.no_dependents()
    }
    fn dependent_rules(&self) -> Vec<RuleRef> {
        self.state.dependents()
    }
    fn set_dependency_rules(&self, rules: &[RuleRef]) {
        self.state.set_dependencies(rules)
    }
    fn no_dependency_rules(&self) -> bool {
        self.state.no_dependencies()
    }
    fn dependency_rules(&self) -> Vec<RuleRef> {
        self.state.dependencies()
    }
    fn as_any(&self) -> &dyn Any {
        self
    }
}
