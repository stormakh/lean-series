#!/usr/bin/env python3
"""Generates crates/promql/src/parser/functions_table.rs from upstream promql/parser/functions.go.

usage: scripts/gen/promql_functions.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'upstream/promql/parser/functions.go')
OUT = os.path.join(ROOT, 'crates/promql/src/parser/functions_table.rs')

VT = {'ValueTypeNone': 'ValueType::None', 'ValueTypeVector': 'ValueType::Vector',
      'ValueTypeScalar': 'ValueType::Scalar', 'ValueTypeMatrix': 'ValueType::Matrix',
      'ValueTypeString': 'ValueType::String'}


def main():
    src = open(SRC).read()
    body = src[src.index('var Functions = map[string]*Function{'):]
    body = body[:body.index('\n}\n')]
    entries = re.findall(r'\n\t"([^"]+)": \{(.*?)\n\t\},', body, re.S)
    if not entries:
        sys.exit('no functions found')
    funcs = []
    for key, fields in entries:
        f = dict(re.findall(r'(\w+):\s*(.*?),\n', fields + '\n'))
        name = f['Name'].strip('"')
        if name != key:
            sys.exit('key %s has name %s' % (key, name))
        args = re.findall(r'ValueType\w+', f.get('ArgTypes', ''))
        funcs.append((name, [VT[a] for a in args], int(f.get('Variadic', '0')), VT[f['ReturnType']],
                      f.get('Experimental', 'false') == 'true'))
    funcs.sort()
    out = ['// Code generated by scripts/gen/promql_functions.py from upstream promql/parser/functions.go.',
           '// DO NOT EDIT.',
           '',
           'use super::functions::FunctionDef;',
           'use super::value::ValueType;',
           '',
           '/// All functions of PromQL with their types, sorted by name; the index is the function id.',
           'pub(crate) static FUNCTION_DEFS: [FunctionDef; %d] = [' % len(funcs)]
    for name, args, variadic, ret, exp in funcs:
        out.append('    FunctionDef { name: "%s", arg_types: &[%s], variadic: %d, return_type: %s, experimental: %s },'
                   % (name, ', '.join(args), variadic, ret, 'true' if exp else 'false'))
    out.append('];')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('wrote %s: %d functions' % (os.path.relpath(OUT, ROOT), len(funcs)))


if __name__ == '__main__':
    main()
