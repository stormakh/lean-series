// Command rustexp translates the expected-entry tables ([]parsedEntry literals) of a Go textparse test file into
// Rust functions returning Vec<textparse::testing::ParsedEntry>, value for value.
//
// Usage (from scripts/gen/textparse): go run ./rustexp <go test file> <out.rs> <Func>...
//
// For every []parsedEntry composite literal inside the named Go functions it writes
// `pub fn <func_snake>_<n>() -> Vec<ParsedEntry>` (n counts from 0 in source order), with the Go line number and
// the other fields of the enclosing table row as a comment. Unknown expressions stop the translation.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strconv"
	"strings"
	"unicode"
)

var fset = token.NewFileSet()

func fail(n ast.Node, format string, args ...any) {
	pos := ""
	if n != nil {
		pos = fset.Position(n.Pos()).String() + ": "
	}
	fmt.Fprintf(os.Stderr, "rustexp: "+pos+format+"\n", args...)
	os.Exit(1)
}

func main() {
	if len(os.Args) < 4 {
		fail(nil, "usage: rustexp <go test file> <out.rs> <Func>...")
	}
	f, err := parser.ParseFile(fset, os.Args[1], nil, 0)
	if err != nil {
		fail(nil, "%v", err)
	}
	want := map[string]bool{}
	for _, n := range os.Args[3:] {
		want[n] = true
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Generated by scripts/gen/textparse/rustexp from upstream/%s. Do not edit.\n",
		strings.TrimPrefix(os.Args[1], "../../../upstream/"))
	out.WriteString("#![allow(dead_code, unused_imports)]\n\n")
	out.WriteString("use model::exemplar::Exemplar;\n")
	out.WriteString("use model::histogram::{custom_values, CounterResetHint, FloatHistogram, Histogram, Span};\n")
	out.WriteString("use model::labels::{empty_labels, from_strings};\n")
	out.WriteString("use model::metadata::MetricType;\n")
	out.WriteString("use textparse::testing::ParsedEntry;\n")
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || !want[fn.Name.Name] {
			continue
		}
		delete(want, fn.Name.Name)
		idx := 0
		var stack []ast.Node
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			if n == nil {
				stack = stack[:len(stack)-1]
				return true
			}
			stack = append(stack, n)
			cl, ok := n.(*ast.CompositeLit)
			if !ok || !isParsedEntrySlice(cl.Type) {
				return true
			}
			fmt.Fprintf(&out, "\n/// Go line %d.", fset.Position(cl.Pos()).Line)
			if row := enclosingRow(stack, cl); row != nil {
				for _, el := range row.Elts {
					kv := el.(*ast.KeyValueExpr)
					if kv.Value == cl {
						continue
					}
					fmt.Fprintf(&out, " `%s: %s`", goSrc(kv.Key), goSrc(kv.Value))
				}
			}
			fmt.Fprintf(&out, "\npub fn %s_%d() -> Vec<ParsedEntry> {\n    vec![\n", snake(fn.Name.Name), idx)
			idx++
			for _, el := range cl.Elts {
				out.WriteString(entry(el.(*ast.CompositeLit), "        "))
			}
			out.WriteString("    ]\n}\n")
			stack = stack[:len(stack)-1]
			return false
		})
		if idx == 0 {
			fail(fn, "%s: no []parsedEntry literal", fn.Name.Name)
		}
	}
	for n := range want {
		fail(nil, "function %s not found", n)
	}
	if err := os.WriteFile(os.Args[2], out.Bytes(), 0o644); err != nil {
		fail(nil, "%v", err)
	}
}

func goSrc(n ast.Node) string {
	var b bytes.Buffer
	_ = format.Node(&b, fset, n)
	return strings.Join(strings.Fields(b.String()), " ")
}

func isParsedEntrySlice(t ast.Expr) bool {
	at, ok := t.(*ast.ArrayType)
	if !ok {
		return false
	}
	id, ok := at.Elt.(*ast.Ident)
	return ok && id.Name == "parsedEntry"
}

// enclosingRow returns the struct literal whose field value is cl, if any.
func enclosingRow(stack []ast.Node, cl *ast.CompositeLit) *ast.CompositeLit {
	if len(stack) < 3 {
		return nil
	}
	kv, ok := stack[len(stack)-2].(*ast.KeyValueExpr)
	if !ok || kv.Value != cl {
		return nil
	}
	row, _ := stack[len(stack)-3].(*ast.CompositeLit)
	return row
}

func snake(s string) string {
	var b strings.Builder
	rs := []rune(s)
	for i, r := range rs {
		if unicode.IsUpper(r) {
			if i > 0 && rs[i-1] != '_' && (unicode.IsLower(rs[i-1]) || (i+1 < len(rs) && unicode.IsLower(rs[i+1]))) {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func goString(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.BasicLit:
		if e.Kind != token.STRING {
			fail(e, "not a string literal")
		}
		s, err := strconv.Unquote(e.Value)
		if err != nil {
			fail(e, "%v", err)
		}
		return s
	case *ast.BinaryExpr:
		if e.Op == token.ADD {
			return goString(e.X) + goString(e.Y)
		}
	}
	fail(e, "unsupported string expression %s", goSrc(e))
	return ""
}

// rustStr is a Rust string literal for valid UTF-8 s.
func rustStr(s string) string {
	if !utf8Valid(s) {
		return rustBytes(s) + " /* not UTF-8 */"
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func utf8Valid(s string) bool {
	return strings.ToValidUTF8(s, "\x00invalid") == s && !strings.Contains(s, "\x00invalid")
}

// rustBytes is a Rust byte string literal.
func rustBytes(s string) string {
	var b strings.Builder
	b.WriteString(`b"`)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"':
			b.WriteString(`\"`)
		case c == '\\':
			b.WriteString(`\\`)
		case c == '\n':
			b.WriteString(`\n`)
		case c < 0x20 || c >= 0x7f:
			fmt.Fprintf(&b, `\x%02x`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// number translates an integer or float constant for a Rust field of type ty (f64, i64, u64, i32, u32).
func number(e ast.Expr, ty string) string {
	switch e := e.(type) {
	case *ast.UnaryExpr:
		if e.Op == token.SUB {
			if strings.HasPrefix(ty, "u") {
				fail(e, "negative value for %s", ty)
			}
			return "-" + number(e.X, ty)
		}
	case *ast.ParenExpr:
		return number(e.X, ty)
	case *ast.BasicLit:
		v := e.Value
		switch e.Kind {
		case token.INT:
			if ty == "f64" {
				if strings.HasPrefix(v, "0x") || strings.HasPrefix(v, "0X") {
					fail(e, "hex float context")
				}
				return v + ".0"
			}
			return v
		case token.FLOAT:
			if ty != "f64" {
				fail(e, "float literal %s for %s", v, ty)
			}
			if strings.HasPrefix(v, ".") {
				v = "0" + v
			}
			if strings.HasSuffix(v, ".") {
				v += "0"
			}
			if _, err := strconv.ParseFloat(v, 64); err != nil {
				fail(e, "%v", err)
			}
			return v
		}
	}
	fail(e, "unsupported number expression %s", goSrc(e))
	return ""
}

func boolean(e ast.Expr) string {
	if id, ok := e.(*ast.Ident); ok && (id.Name == "true" || id.Name == "false") {
		return id.Name
	}
	fail(e, "unsupported bool %s", goSrc(e))
	return ""
}

func sel(e ast.Expr) (string, string) {
	s, ok := e.(*ast.SelectorExpr)
	if !ok {
		fail(e, "expected pkg.Name, got %s", goSrc(e))
	}
	return s.X.(*ast.Ident).Name, s.Sel.Name
}

func fields(cl *ast.CompositeLit) []*ast.KeyValueExpr {
	var out []*ast.KeyValueExpr
	for _, el := range cl.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			fail(el, "unkeyed struct field")
		}
		out = append(out, kv)
	}
	return out
}

func key(kv *ast.KeyValueExpr) string {
	return kv.Key.(*ast.Ident).Name
}

func entry(cl *ast.CompositeLit, ind string) string {
	var b strings.Builder
	b.WriteString(ind + "ParsedEntry {\n")
	in := ind + "    "
	for _, kv := range fields(cl) {
		switch key(kv) {
		case "m":
			fmt.Fprintf(&b, "%sm: %s.to_vec(),\n", in, rustBytes(goString(kv.Value)))
		case "help", "unit", "comment":
			fmt.Fprintf(&b, "%s%s: %s.into(),\n", in, key(kv), rustStr(goString(kv.Value)))
		case "typ":
			pkg, name := sel(kv.Value)
			if pkg != "model" || !strings.HasPrefix(name, "MetricType") {
				fail(kv, "unsupported type %s", goSrc(kv.Value))
			}
			fmt.Fprintf(&b, "%styp: MetricType::%s,\n", in, strings.TrimPrefix(name, "MetricType"))
		case "v":
			fmt.Fprintf(&b, "%sv: %s,\n", in, number(kv.Value, "f64"))
		case "st":
			fmt.Fprintf(&b, "%sst: %s,\n", in, number(kv.Value, "i64"))
		case "t":
			c, ok := kv.Value.(*ast.CallExpr)
			if !ok || c.Fun.(*ast.Ident).Name != "int64p" {
				fail(kv, "unsupported t %s", goSrc(kv.Value))
			}
			fmt.Fprintf(&b, "%st: Some(%s),\n", in, number(c.Args[0], "i64"))
		case "lset":
			fmt.Fprintf(&b, "%slset: %s,\n", in, labelsExpr(kv.Value))
		case "es":
			fmt.Fprintf(&b, "%ses: vec![\n", in)
			for _, el := range kv.Value.(*ast.CompositeLit).Elts {
				b.WriteString(exemplarExpr(el.(*ast.CompositeLit), in+"    "))
			}
			fmt.Fprintf(&b, "%s],\n", in)
		case "shs":
			fmt.Fprintf(&b, "%sshs: Some(%s),\n", in, histogramExpr(kv.Value, "Histogram", in))
		case "fhs":
			fmt.Fprintf(&b, "%sfhs: Some(%s),\n", in, histogramExpr(kv.Value, "FloatHistogram", in))
		default:
			fail(kv, "unknown parsedEntry field %s", key(kv))
		}
	}
	b.WriteString(in + "..Default::default()\n")
	b.WriteString(ind + "},\n")
	return b.String()
}

func labelsExpr(e ast.Expr) string {
	c, ok := e.(*ast.CallExpr)
	if !ok {
		fail(e, "unsupported labels %s", goSrc(e))
	}
	pkg, name := sel(c.Fun)
	if pkg != "labels" {
		fail(e, "unsupported labels %s", goSrc(e))
	}
	switch name {
	case "EmptyLabels":
		return "empty_labels()"
	case "FromStrings":
		var parts []string
		for _, a := range c.Args {
			// string(model.MetricTypeX) is the type name, for example "gauge".
			if conv, ok := a.(*ast.CallExpr); ok && len(conv.Args) == 1 {
				if id, ok := conv.Fun.(*ast.Ident); ok && id.Name == "string" {
					pkg, name := sel(conv.Args[0])
					if pkg != "model" || !strings.HasPrefix(name, "MetricType") {
						fail(a, "unsupported label value %s", goSrc(a))
					}
					parts = append(parts, "MetricType::"+strings.TrimPrefix(name, "MetricType")+".as_str()")
					continue
				}
			}
			parts = append(parts, rustStr(goString(a)))
		}
		return "from_strings(&[" + strings.Join(parts, ", ") + "])"
	}
	fail(e, "unsupported labels %s", goSrc(e))
	return ""
}

func exemplarExpr(cl *ast.CompositeLit, ind string) string {
	var parts []string
	for _, kv := range fields(cl) {
		switch key(kv) {
		case "Labels":
			parts = append(parts, "labels: "+labelsExpr(kv.Value))
		case "Value":
			parts = append(parts, "value: "+number(kv.Value, "f64"))
		case "HasTs":
			parts = append(parts, "has_ts: "+boolean(kv.Value))
		case "Ts":
			parts = append(parts, "ts: "+number(kv.Value, "i64"))
		default:
			fail(kv, "unknown exemplar field %s", key(kv))
		}
	}
	parts = append(parts, "..Default::default()")
	return ind + "Exemplar { " + strings.Join(parts, ", ") + " },\n"
}

func histogramExpr(e ast.Expr, typ, ind string) string {
	u, ok := e.(*ast.UnaryExpr)
	if !ok || u.Op != token.AND {
		fail(e, "expected &histogram.%s{...}", typ)
	}
	cl := u.X.(*ast.CompositeLit)
	if pkg, name := sel(cl.Type); pkg != "histogram" || name != typ {
		fail(e, "expected histogram.%s, got %s.%s", typ, pkg, name)
	}
	countTy, bucketTy := "u64", "i64"
	if typ == "FloatHistogram" {
		countTy, bucketTy = "f64", "f64"
	}
	in := ind + "    "
	var b strings.Builder
	b.WriteString(typ + " {\n")
	for _, kv := range fields(cl) {
		switch k := key(kv); k {
		case "CounterResetHint":
			pkg, name := sel(kv.Value)
			if pkg != "histogram" {
				fail(kv, "unsupported hint")
			}
			fmt.Fprintf(&b, "%scounter_reset_hint: CounterResetHint::%s,\n", in, name)
		case "Schema":
			fmt.Fprintf(&b, "%sschema: %s,\n", in, number(kv.Value, "i32"))
		case "ZeroThreshold", "Sum":
			fmt.Fprintf(&b, "%s%s: %s,\n", in, snake(k), number(kv.Value, "f64"))
		case "ZeroCount", "Count":
			fmt.Fprintf(&b, "%s%s: %s,\n", in, snake(k), number(kv.Value, countTy))
		case "PositiveSpans", "NegativeSpans":
			var spans []string
			for _, el := range kv.Value.(*ast.CompositeLit).Elts {
				var off, length string = "0", "0"
				for _, skv := range fields(el.(*ast.CompositeLit)) {
					switch key(skv) {
					case "Offset":
						off = number(skv.Value, "i32")
					case "Length":
						length = number(skv.Value, "u32")
					default:
						fail(skv, "unknown span field")
					}
				}
				spans = append(spans, "Span::new("+off+", "+length+")")
			}
			fmt.Fprintf(&b, "%s%s: vec![%s],\n", in, snake(k), strings.Join(spans, ", "))
		case "PositiveBuckets", "NegativeBuckets":
			fmt.Fprintf(&b, "%s%s: vec![%s],\n", in, snake(k), numberList(kv.Value, bucketTy))
		case "CustomValues":
			fmt.Fprintf(&b, "%scustom_values: custom_values(&[%s]),\n", in, numberList(kv.Value, "f64"))
		default:
			fail(kv, "unknown histogram field %s", k)
		}
	}
	b.WriteString(in + "..Default::default()\n")
	b.WriteString(ind + "}")
	return b.String()
}

func numberList(e ast.Expr, ty string) string {
	var parts []string
	for _, el := range e.(*ast.CompositeLit).Elts {
		parts = append(parts, number(el, ty))
	}
	return strings.Join(parts, ", ")
}
